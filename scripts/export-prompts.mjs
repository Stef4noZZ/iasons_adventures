// Builds docs/prompts/<id>.md: copy-paste image prompts for every page. Run: npm run prompts [-- <story-id>]
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const series = JSON.parse(readFileSync(join(root, "public", "series.json"), "utf8"));
// Every book folder, listed in series.json or not: prompts are needed before the pictures exist.
const allBooks = readdirSync(join(root, "public", "stories"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(join(root, "public", "stories", entry.name, "story.json")))
  .map((entry) => entry.name);
const ids = process.argv[2] ? [process.argv[2]] : [...series.stories, ...allBooks.filter((id) => !series.stories.includes(id))];
mkdirSync(join(root, "docs", "prompts"), { recursive: true });

for (const id of ids) {
  const story = JSON.parse(readFileSync(join(root, "public", "stories", id, "story.json"), "utf8"));
  const shared = series.art_direction ?? {};
  const art = {
    ...story.art_direction,
    negative_prompt: story.art_direction.negative_prompt ?? shared.negative_prompt,
    composition_note: story.art_direction.composition_note ?? shared.composition_note,
    characters: { ...shared.characters, ...story.art_direction.characters },
  };
  const [w] = story.trim_size_cm;
  const px = Math.round(((w * 10 + 6) / 25.4) * 300);

  const full = (scene, characters) => [
    art.style_prompt,
    `Scene: ${scene}`,
    ...characters.map((name) => art.characters[name]),
    art.composition_note,
  ].join("\n\n");

  const items = [["Cover", "cover.png", story.cover_prompt, story.cover_characters ?? [], story.title.en]];
  for (const page of story.pages) {
    items.push([`Page ${page.number}`, page.image, page.image_prompt, page.characters ?? [], page.text.en.mode1]);
  }
  const missing = items.filter(([, , prompt]) => !prompt).map(([label]) => label);
  if (missing.length) throw new Error(`${id}: no image prompt for ${missing.join(", ")}`);

  const out = `# Image prompts: ${story.title.en}

Generated by \`npm run prompts\` from \`public/stories/${id}/story.json\`. Edit the prompts there, not here.

## How to use

1. Start with the **character sheets** below. Generate each character on its own first, with a plain background, and keep the versions you like. For Jason, attach the reference photo of your son (face and hair only). If you already made Jason and Phoebus for another book, attach those finished images instead, so they look the same in every book.
2. Generate the **cover** next. Once you like it, attach the cover and the character images as references for every other page so the style and characters stay the same.
3. Each prompt below is complete and can be pasted as is. It already contains the style, the characters in the scene and the composition rule.
4. Paste the **negative prompt** if the tool has a field for it; otherwise add "no text, no letters, no watermark".
5. Generate several variations of each page and choose together. If a character drifts, re-attach the character image and regenerate.
6. Keep the **safe area** rule: nothing important in the lowest 35-40% of the picture, the text is printed there.
7. Final files: square, at least **${px} x ${px} px** (upscale if the tool gives less; 300 dpi at ${w} cm plus bleed), PNG, with no text inside. Name them exactly as shown (\`cover.png\`, \`page_01.png\` ...) and save them to \`assets/stories/${id}/images/\`.
8. Run \`npm run images\` then \`npm run validate\`. The app and the PDF pick them up; no code changes are needed.

Keep the reference photos of your son private (they stay out of git in \`assets/characters/private_reference_photos/\`).

## Style (used in every prompt)

${art.style_prompt}

**Negative prompt:** ${art.negative_prompt}

**Composition:** ${art.composition_note}

## Character sheets

Generate each on a plain soft background, full body, front and three-quarter view, in the style above.

${Object.entries(art.characters).map(([name, text]) => `### ${name}\n\n${text}`).join("\n\n")}

## Pages

${items.map(([label, file, prompt, characters, text]) => `### ${label} (\`${file}\`)

*Story text:* ${text}

\`\`\`text
${full(prompt, characters)}
\`\`\`
`).join("\n")}`;

  const file = join(root, "docs", "prompts", `${id}.md`);
  writeFileSync(file, out);
  console.log(file);
}
